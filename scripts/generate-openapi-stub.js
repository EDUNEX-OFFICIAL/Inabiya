#!/usr/bin/env node
/**
 * OpenAPI stub path (Phase 0 P1 leftover).
 * Copies Docs/openapi.stub.yaml → apps/api/openapi/openapi.json companion marker.
 * Full Nest Swagger generation is post-dev / optional ADR.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'Docs', 'openapi.stub.yaml');
const outDir = path.join(root, 'apps', 'api', 'openapi');
const outYaml = path.join(outDir, 'openapi.stub.yaml');
const marker = path.join(outDir, 'README.md');

if (!fs.existsSync(src)) {
  console.error('Missing Docs/openapi.stub.yaml');
  process.exit(1);
}
fs.mkdirSync(outDir, { recursive: true });
fs.copyFileSync(src, outYaml);
fs.writeFileSync(
  marker,
  `# OpenAPI stub\n\nGenerated by \`node scripts/generate-openapi-stub.js\`.\nSource of truth: \`Docs/openapi.stub.yaml\`.\n\nNot a live Swagger UI — expand later with \`@nestjs/swagger\` if Product asks.\n`,
);
console.log('openapi stub →', outYaml);
